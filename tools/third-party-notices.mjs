// Writes THIRD_PARTY_NOTICES.md: every third-party package that ships inside Ironleaf (bundled into the window or
// the main side, or copied beside it), with its version, licence and licence text, found by walking each root
// package's dependencies in node_modules. `--check` exits 1 if any licence is outside the AGPL-compatible list.
//   node tools/third-party-notices.mjs [--check]
import { existsSync, readFileSync, readdirSync, realpathSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
// What the app imports (src/**) and what the release stages beside it. Electron (MIT) ships its own notices for
// Chromium, Node.js and their dependencies (LICENSE and LICENSES.chromium.html beside the program).
export const ROOTS = [
  '@earendil-works/pi-ai', 'd3-force', 'echarts', 'jose', 'onnxruntime-web', 'yaml',
  'react', 'react-dom', 'katex', 'markdown-it', 'markdown-it-footnote', 'mermaid', 'ssh2',
  '@codemirror/autocomplete', '@codemirror/commands', '@codemirror/lang-markdown', '@codemirror/lang-yaml', '@codemirror/language',
  '@codemirror/language-data', '@codemirror/search', '@codemirror/state', '@codemirror/view', '@lezer/highlight', '@lezer/common', '@lezer/markdown',
];
// Compatible with distribution under AGPL-3.0-or-later (permissive, or weak copyleft kept file-level).
export const COMPATIBLE = /^(MIT|ISC|BSD-2-Clause|BSD-3-Clause|Apache-2\.0|0BSD|OFL-1\.1|Unlicense|CC0-1\.0|BlueOak-1\.0\.0|Python-2\.0|PSF-2\.0|Zlib|MPL-2\.0|\(MPL-2\.0 OR Apache-2\.0\)|\(MIT OR Apache-2\.0\)|\(Apache-2\.0 OR MIT\)|\(MIT OR CC0-1\.0\)|\(BSD-2-Clause OR MIT OR Apache-2\.0\)|\(MIT AND Zlib\)|\(MIT AND BSD-3-Clause\)|\(WTFPL OR MIT\)|LGPL-3\.0-or-later|AGPL-3\.0-or-later|GPL-3\.0-or-later)$/;

export function collect() {
  const found = new Map();
  const visit = (name, fromDir) => {
    let dir = fromDir;
    for (;;) {
      const candidate = path.join(dir, 'node_modules', name);
      if (existsSync(path.join(candidate, 'package.json'))) {
        const real = realpathSync(candidate);
        if (found.has(real)) return;
        const meta = JSON.parse(readFileSync(path.join(real, 'package.json'), 'utf8'));
        const license = typeof meta.license === 'string' ? meta.license : meta.license?.type ?? meta.licenses?.[0]?.type ?? '';
        const licFile = readdirSync(real).find((f) => /^(licen[cs]e|copying|notice)(\.|$|-)/i.test(f));
        const text = licFile ? readFileSync(path.join(real, licFile), 'utf8').trim() : '';
        // No licence field but an MIT licence file (khroma): named from the file.
        const named = license || (/^(the )?MIT License/i.test(text) ? 'MIT' : '');
        found.set(real, { name: meta.name ?? name, version: meta.version ?? '?', license: named, repo: typeof meta.repository === 'string' ? meta.repository : meta.repository?.url ?? '', text });
        for (const dep of Object.keys({ ...(meta.dependencies ?? {}), ...(meta.optionalDependencies ?? {}) })) visit(dep, real);
        return;
      }
      const up = path.dirname(dir);
      if (up === dir) return;
      dir = up;
    }
  };
  for (const r of ROOTS) visit(r, root);
  return [...found.values()].sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const list = collect();
  const bad = list.filter((p) => !COMPATIBLE.test(p.license));
  if (process.argv.includes('--check')) {
    for (const p of bad) console.log(`not on the compatible list: ${p.name}@${p.version} (${p.license || 'none'})`);
    console.log(`${list.length} packages, ${bad.length} to review`);
    process.exit(bad.length ? 1 : 0);
  }
  const counts = {};
  for (const p of list) counts[p.license || 'none'] = (counts[p.license || 'none'] ?? 0) + 1;
  let out = `# Third-party notices\n\nIronleaf is licensed under AGPL-3.0-or-later (see LICENSE). It includes the third-party software below, each under its own licence. Generated by \`node tools/third-party-notices.mjs\` from \`node_modules\`; models, fonts and other bundled files are listed in ASSETS.md. Electron (MIT) carries its own notices for Chromium and Node.js (LICENSE and LICENSES.chromium.html beside the installed program).\n\n## Summary\n\n| Licence | Packages |\n| --- | --- |\n`;
  for (const [l, n] of Object.entries(counts).sort((a, b) => b[1] - a[1])) out += `| ${l} | ${n} |\n`;
  out += `\n## Packages\n\n| Package | Version | Licence |\n| --- | --- | --- |\n`;
  for (const p of list) out += `| ${p.name} | ${p.version} | ${p.license || 'none stated'} |\n`;
  out += `\n## Licence texts\n`;
  for (const p of list) out += `\n### ${p.name} ${p.version} (${p.license || 'none stated'})\n\n${p.repo ? p.repo.replace(/^git\+/, '') + '\n\n' : ''}${p.text ? '```text\n' + p.text.replace(/```/g, "'''") + '\n```' : '_No licence file in the package; see the licence named above._'}\n`;
  writeFileSync(path.join(root, 'THIRD_PARTY_NOTICES.md'), out);
  console.log(`THIRD_PARTY_NOTICES.md: ${list.length} packages; ${bad.length} to review: ${bad.map((p) => `${p.name} (${p.license || 'none'})`).join(', ') || 'none'}`);
}
